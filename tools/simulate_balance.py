"""Generate a deterministic economy report directly from central Luau balance values."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "src" / "shared" / "Config" / "GameConfig.luau"
OUTPUT = ROOT / "docs" / "BALANCE_REPORT.md"


def number(source: str, key: str) -> float:
    """Read one top-level numeric assignment from GameConfig."""
    match = re.search(rf"\b{re.escape(key)}\s*=\s*([0-9]+(?:\.[0-9]+)?)", source)
    if not match:
        raise ValueError(f"Missing numeric balance key: {key}")
    return float(match.group(1))


def fmt(value: float) -> str:
    """Format whole and fractional values consistently in the generated report."""
    return str(int(value)) if value.is_integer() else f"{value:.2f}"


def main() -> None:
    """Calculate early-loop production, leveling and adoption tradeoffs and write a review artifact."""
    source = CONFIG.read_text(encoding="utf-8-sig")
    interval = number(source, "FoodProductionInterval")
    per_drop = number(source, "FoodPerDrop")
    feeding_xp = number(source, "FeedingXPReward")
    feeding_cooldown = number(source, "FeedingXPCooldown")
    xp_base = number(source, "XPBase")
    xp_step = number(source, "XPPerLevel")
    adoption_bonus = number(source, "AdoptionLevelBonus")
    start_cash = number(source, "StartingCash")
    kennel = number(source, "KennelCost")
    food_hour = 3600 / interval * per_drop
    feeds_hour = 3600 / feeding_cooldown
    xp_hour = feeds_hour * feeding_xp

    levels = []
    for level in (1, 3, 5, 10, 20):
        cumulative = sum(xp_base + (step - 1) * xp_step for step in range(1, level))
        feeds = cumulative / feeding_xp
        minutes = feeds * feeding_cooldown / 60
        value_multiplier = 1 + (level - 1) * adoption_bonus
        levels.append((level, cumulative, feeds, minutes, value_multiplier))

    costs = [float(value) for value in re.findall(r"\bCost\s*=\s*([0-9]+(?:\.[0-9]+)?)", source)]
    report = [
        "# Economy balance report",
        "",
        "Generated by tools/simulate_balance.py from GameConfig.luau.",
        "",
        "## Early loop",
        "",
        f"- Starting cash after kennel: **{fmt(start_cash - kennel)}**.",
        f"- Passive production: **{fmt(food_hour)} food/hour** before collection/storage limits.",
        f"- Feeding opportunities per pet: **{fmt(feeds_hour)}/hour**.",
        f"- Base feeding progression: **{fmt(xp_hour)} XP/hour per actively fed pet**.",
        "",
        "## Level investment",
        "",
        "| Level | Total XP | Successful feeds | Minimum active-care minutes | Adoption level multiplier |",
        "| ---: | ---: | ---: | ---: | ---: |",
    ]
    for level, xp, feeds, minutes, multiplier in levels:
        report.append(f"| {level} | {fmt(xp)} | {fmt(feeds)} | {fmt(minutes)} | {fmt(multiplier)}x |")
    report += [
        "",
        "## Upgrade cost ladder",
        "",
        "- Configured costs: " + ", ".join(fmt(cost) for cost in costs) + ".",
        "- Review goal: a normal adoption must always provide recovery progress, while raised pets should reward waiting.",
        "- Manual care XP accelerates engagement but remains bounded by independent per-pet cooldowns.",
        "- Adopter request matches add 35% temporarily; normal adoption stays available.",
        "",
        "## Review flags",
        "",
    ]
    flags = []
    if start_cash < kennel:
        flags.append("- **BLOCKER:** starting cash cannot buy the kennel.")
    if food_hour < feeds_hour:
        flags.append("- Food production cannot support one pet's feeding cadence.")
    if not costs:
        flags.append("- No upgrade costs were discovered.")
    if not flags:
        flags.append("- No structural progression blocker detected by the deterministic checks.")
    report.extend(flags)
    OUTPUT.write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
